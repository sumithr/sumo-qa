class HostSamplingClient:
    """Async LLM client that delegates to the MCP host via the sampling spec.

    The host (Claude Code, Copilot, Cursor, etc.) decides which model runs the
    completion - whatever the user has configured. The MCP server only supplies
    the QA-discipline system prompt and a guardrailed user prompt.

    If the host does not advertise sampling support, `session.create_message`
    raises and the caller is expected to fall back gracefully.
    """

    model_name = "host-llm-via-sampling"

    def __init__(self, session: object, max_tokens: int = 1024) -> None:
        self._session = session
        self._max_tokens = max_tokens

    async def complete(self, system_prompt: str, user_prompt: str) -> LLMResponse:
        try:
            from mcp.types import SamplingMessage, TextContent
        except ImportError as exc:  # pragma: no cover - mcp SDK is a hard dep
            raise RuntimeError("mcp SDK is required for HostSamplingClient") from exc

        message = SamplingMessage(
            role="user",
            content=TextContent(type="text", text=user_prompt),
        )
        result = await self._session.create_message(
            messages=[message],
            max_tokens=self._max_tokens,
            system_prompt=system_prompt,
        )
        text = ""
        if hasattr(result, "content"):
            content = result.content
            if hasattr(content, "text"):
                text = content.text or ""
            elif isinstance(content, list) and content:
                first = content[0]
                if hasattr(first, "text"):
                    text = first.text or ""
        model_name = getattr(result, "model", self.model_name)
        return LLMResponse(
            content=text,
            model=model_name,
            metadata={
                "mode": "host-sampling",
                "external_calls": "true",
                "note": "Generated by the MCP host's configured LLM via sampling.",
            },
        )


