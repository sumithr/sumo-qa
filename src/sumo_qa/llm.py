from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol


@dataclass(frozen=True)
class LLMResponse:
    content: str
    model: str
    metadata: dict[str, str]


class LLMClient(Protocol):
    def complete(self, system_prompt: str, user_prompt: str) -> LLMResponse:
        """Generate a response for QA tooling."""


class AsyncLLMClient(Protocol):
    async def complete(self, system_prompt: str, user_prompt: str) -> LLMResponse:
        """Generate a response for QA tooling using the host's configured LLM."""


class MockLLMClient:
    """Deterministic client for local development and unit tests.

    Returns no analysis content - the response is an explicit signal that no
    external LLM is configured. Consumers should treat the empty content as
    "rule-based output only" rather than render mock text as if it were analysis.
    """

    model_name = "deterministic-no-llm"

    def complete(self, system_prompt: str, user_prompt: str) -> LLMResponse:
        del system_prompt, user_prompt
        return LLMResponse(
            content="",
            model=self.model_name,
            metadata={
                "mode": "deterministic",
                "external_calls": "false",
                "note": "No external LLM is configured. Output is rule-based only.",
            },
        )


